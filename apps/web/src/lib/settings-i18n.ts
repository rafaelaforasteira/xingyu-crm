export type SettingsCopy = { [K in keyof (typeof dictionaries)["pt-BR"]]: string };

export function settingsText(locale: SettingsLocale | string | undefined): SettingsCopy {
  if (locale === "en" || locale === "zh-CN" || locale === "zh-HK") return dictionaries[locale];
  return dictionaries["pt-BR"];
}

export function interpolate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}
