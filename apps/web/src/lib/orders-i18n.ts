export const orderEnumLabel = (value: string | null | undefined, locale: OrderLocale) =>
  value
    ? labels[value]?.[locale] ||
      value
        .toLowerCase()
        .replaceAll("_", " ")
        .replace(/^./, (c) => c.toUpperCase())
    : "—";
export const formatOrderCurrency = (
  value: number,
  currency = "BRL",
  locale: OrderLocale = "pt-BR",
) => new Intl.NumberFormat(locale, { style: "currency", currency }).format(value);
export const formatOrderDate = (value: string | null | undefined, locale: OrderLocale) =>
  value
    ? new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(
        new Date(value),
      )
    : "—";
